/** Flatten DRF / Supabase / network error payloads for toast copy. */
function formatApiError(err, fallback = "Request failed") {
	if (!(err instanceof ApiError)) return messageFromUnknown(err) || fallback;
	const nested = messageFromUnknown(err.body);
	if (nested && nested !== err.message) {
		if (!err.message || /^(request failed|backend request failed\.?|registration failed|login failed)$/i.test(err.message)) return nested;
	}
	const body = err.body;
	if (typeof body === "string" && body.trim()) return body;
	if (body && typeof body === "object") {
		const record = body;
		if (typeof record.detail === "string") return record.detail;
		if (Array.isArray(record.detail)) return record.detail.map(String).join(" ");
		const bits = [];
		for (const [key, value] of Object.entries(record)) {
			if (key === "message" || key === "name" || key === "stack") continue;
			if (key === "store" && value && typeof value === "object") {
				for (const [sk, sv] of Object.entries(value)) bits.push(`${sk}: ${Array.isArray(sv) ? sv.join(" ") : String(sv)}`);
				continue;
			}
			if (Array.isArray(value)) bits.push(`${key}: ${value.join(" ")}`);
			else if (typeof value === "string") bits.push(`${key}: ${value}`);
		}
		if (bits.length) return bits.join(" · ");
	}
	return nested || err.message || fallback;
}
